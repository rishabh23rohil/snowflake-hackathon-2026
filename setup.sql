SELECT 'HR_ATTRITION' AS TBL, COUNT(*) AS ROW_COUNT FROM HACKATHON.DATA.HR_ATTRITION
UNION ALL SELECT 'USER_ADOPTION', COUNT(*) FROM HACKATHON.DATA.USER_ADOPTION
UNION ALL SELECT 'CONTRACT_METADATA', COUNT(*) FROM HACKATHON.DATA.CONTRACT_METADATA
UNION ALL SELECT 'ACCESS_LOGS', COUNT(*) FROM HACKATHON.DATA.ACCESS_LOGS
UNION ALL SELECT 'ENGAGEMENT_LOGS', COUNT(*) FROM HACKATHON.DATA.ENGAGEMENT_LOGS;
